// Lists Poly Haven (CC0) 3D models that suit a desert / ruined-yard map and writes them to
// docs/POLYHAVEN_MODELS.md. Run from the project root: npm run assets:list
// Uses Poly Haven's public API (https://api.polyhaven.com). ASCII only on purpose.
import { writeFile } from "node:fs/promises";

const API = "https://api.polyhaven.com";
const WANT =
  /rock|boulder|stone|rubble|pebble|crate|pallet|plank|wood|barrel|dead|cactus|shrub|bush|desert|dry|wall|sandbag|tire|concrete|brick|ruin|debris|junk|sand|cliff|log|stump|branch|grass|weed|palm|metal|rust/i;

const res = await fetch(`${API}/assets?t=models`);
if (!res.ok) throw new Error(`Poly Haven answered ${res.status}`);
const all = await res.json();

const rows = [];
for (const [id, a] of Object.entries(all)) {
  const text = [id, a.name, ...(a.categories ?? []), ...(a.tags ?? [])].join(" ");
  if (!WANT.test(text)) continue;
  rows.push({
    id,
    name: a.name ?? id,
    cats: (a.categories ?? []).join(", "),
    tags: (a.tags ?? []).slice(0, 6).join(", "),
    tris: a.polycount ?? "",
  });
}
rows.sort((x, y) => x.id.localeCompare(y.id));

const lines = rows.map((r) => `| ${r.id} | ${r.name} | ${r.tris} | ${r.cats} | ${r.tags} |`);
const md =
  `# Poly Haven models that may suit the maps (CC0)\n\n` +
  `Generated by tools/assets/list-models.mjs. ${rows.length} of ${Object.keys(all).length} models.\n\n` +
  `| id | name | polycount | categories | tags |\n|---|---|---|---|---|\n` +
  lines.join("\n") +
  "\n";
await writeFile("docs/POLYHAVEN_MODELS.md", md);

// Short form for the chat: id, name, polycount.
console.log(`${rows.length} candidates (full table in docs/POLYHAVEN_MODELS.md)`);
for (const r of rows) console.log(`${r.id} | ${r.name} | ${r.tris}`);
